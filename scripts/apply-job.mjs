let context, page;
try {
  ({ context, page } = dice
    ? await openContext(DICE_PLATFORM, { headed: !!flags.headed, flags, dir: DICE_PROFILE })
    : await openContext('linkedin', { headed: !!flags.headed, flags }));
} catch (err) {
  if (err instanceof ProfileBusyError) {
    log(`SKIPPED: ${err.message}`);
    logAction({ action: 'apply.busy', source: dice ? 'dice' : 'linkedin', job_id: id, detail: { mode: dryRun ? 'dry-run' : 'submit', exit: 3 } });
    out({ success: false, profileBusy: true, job_id: id });
    process.exit(3);
  }
  throw err;
}

let code = 1;
let result = { outcome: 'error' };
// Set right before any Submit click. After it, an exception can never be recorded as a
// plain error: it becomes submit-unverified, which blocks a retry (a retry could send a
// duplicate application): one was sent, then a post-submit click timed out.
let submitClicked = false;
// The company-site URL the run reached, kept on an error too: the next run starts there (recordedAtsUrl).
let reachedAts = null;
try {
  if (dice) [code, result] = await runDice();
  else [code, result] = await runLinkedIn();
} catch (err) {
  await screenshot(page, 'error').catch(() => {});
  [code, result] = submitClicked
    ? [6, { outcome: 'submit-unverified', detail: `error after Submit was clicked: ${err.message.slice(0, 250)}. Check ${dice ? 'Dice > Applied Jobs' : 'LinkedIn > My jobs > Applied'} by hand; never retry` }]
    // A fill that needs the operator's answer (a list without the answer, fillOne): asked like any open
    // question, nothing sent.
    : err.needs ? [4, { outcome: 'needs_answers', detail: err.needs, ...(reachedAts ? { ats_url: reachedAts } : {}) }]
    : [1, { outcome: 'error', detail: err.message.slice(0, 300), ...(reachedAts ? { ats_url: reachedAts } : {}) }];
} finally {
  await context.close().catch(() => {});
}
finish(code, result);

async function runDice() {
  let resp = await page.goto(diceJobUrl(diceGuid(id)), { waitUntil: 'domcontentloaded' });
  recordPost('dice_apply', 'apply_page_loads_per_day', { jobId: id, dryRun, ...loadMeta });
  await diceSettle(page);
  let v = await page.evaluate(collectDiceView, DICE_SEL);
  let verdict = resp?.status() === 403 ? 'blocked' : classifyDicePage({ title: v.page_title, text: v.text, url: page.url(), loggedOut: v.signed_out && !v.signed_in, cardCount: 1 });
  // A signed-out job page is checked on the home feed before it halts Dice, as the tick does (the job
  // page alone once halted Dice while the session was fine). Signed in there, the job
  // page loads again and the run goes on: the wizard's own sign-in redirect still stops a real
  // expiry (exit 5, no halt). Signed out there too, Dice halts as before.
  if (verdict === 'login' && !/\/(login|sign-?in)\b/i.test(page.url())) {
    await screenshot(page, 'job-login-unconfirmed');
    if (await signedInAtHome(page).catch(() => false)) {
      resp = await page.goto(diceJobUrl(diceGuid(id)), { waitUntil: 'domcontentloaded' });
      recordPost('dice_apply', 'apply_page_loads_per_day', { jobId: id, dryRun, ...loadMeta });
      await diceSettle(page);
      v = await page.evaluate(collectDiceView, DICE_SEL);
      verdict = resp?.status() === 403 ? 'blocked' : classifyDicePage({ title: v.page_title, text: v.text, url: page.url(), loggedOut: false, cardCount: 1 });
    }
  }
  if (['blocked', 'checkpoint', 'login'].includes(verdict)) {
    await screenshot(page, `job-${verdict}`);
    loop.halt_until = haltUntil(verdict === 'checkpoint' ? 'checkpoint' : verdict === 'login' ? 'login-lost' : 'blocked', Date.now(), tz(), schedule().reset_hour ?? 4);
    return [1, { outcome: 'error', detail: `Dice ${verdict}: Dice halted until ${loop.halt_until}${verdict === 'login' ? ' (log in by hand: npm run dice -- login)' : ''}` }];
  }
  await screenshot(page, 'job');
  const apply = diceApplyTypeOf({ label: v.apply_label, href: v.apply_href });
  if (diceAlreadyApplied({ label: v.apply_label, headerText: v.header_text })) return [7, { outcome: 'already-applied', detail: 'Dice shows this job as applied' }];
  if (!apply) return [5, { outcome: 'manual', detail: 'no apply control (closed, or the page changed)' }];
  if (apply.type !== 'dice-easy') return diceExternalApply(page, apply);
  const [c, r] = await diceEasyApply(page, apply);
  if (diceResumeReplaced) Object.assign(r, await checkDiceProfileResume(page).catch((err) => ({ profile_resume_check_error: err.message.slice(0, 200) })));
  return [c, r];
}

async function runLinkedIn() {
  let code = 1;
  let result = { outcome: 'error' };
  // A re-run of a company-site role starts from the application URL its last run recorded: no
  // LinkedIn page load just to find it again. --via-linkedin takes the old path.
  // --ats-url <url>: start this one run at a known application page (a job-board Apply that reaches
  // the board's index, not the job's own page). Only an https company page, never LinkedIn or Dice.
  const atsUrl = typeof flags['ats-url'] === 'string' ? flags['ats-url'] : null;
  const atsHost = (() => { try { const u = new URL(atsUrl); return u.protocol === 'https:' ? u.hostname.toLowerCase() : null; } catch { return null; } })();
  const forced = atsHost && !/(^|\.)(linkedin|dice)\.com$/.test(atsHost) ? atsUrl : null;
  if (flags['ats-url'] && !forced) log(`--ats-url ignored (an https company page only, never LinkedIn or Dice): ${flags['ats-url']}`);
  if (forced) { log(`starting from --ats-url, LinkedIn not loaded: ${forced}`); return externalApply(context, page, { url: forced }); }
  const recorded = flags['via-linkedin'] ? null : recordedAtsUrl(job.application, (dir) => readJson(join(dir, 'result.json')));
  if (recorded) {
    log(`starting from the recorded application URL, LinkedIn not loaded: ${recorded}`);
    return externalApply(context, page, { url: recorded });
  }
  await page.goto(`https://www.linkedin.com/jobs/view/${id}/`, { waitUntil: 'domcontentloaded' });
  recordPost('linkedin_apply', 'apply_page_loads_per_day', { jobId: id, dryRun, ...loadMeta });
  await page.waitForTimeout(jitter([3500, 4500]));
  if (/\/(checkpoint|authwall)/.test(page.url()) || await isLoggedOut(page)) {
    const checkpoint = /\/(checkpoint|authwall)/.test(page.url());
    state.halt_until = haltUntil(checkpoint ? 'checkpoint' : 'login-lost', Date.now(), tz(), schedule().reset_hour ?? 4);
    [code, result] = [1, { outcome: 'error', detail: checkpoint ? 'checkpoint: halted 7 days (runbook §4)' : 'login lost: log in by hand (npm run jobs -- login)' }];
  } else {
    const v = await page.evaluate(collectView, SEL_ARG);
    const apply = applyTypeOf({ label: v.apply_label, href: v.apply_href });
    await screenshot(page, 'job');
    if (alreadyAppliedIn(v.main_text)) [code, result] = [7, { outcome: 'already-applied', detail: 'LinkedIn shows this job as applied' }];
    // A closed posting is not work for the user: record it closed.
    else if (!apply && /no longer accepting applications/i.test(v.main_text || '')) [code, result] = [5, { outcome: 'closed', detail: 'LinkedIn: No longer accepting applications' }];
    else if (!apply) [code, result] = [5, { outcome: 'manual', detail: 'no apply control (closed, or the page changed)' }];
    else if (apply.type === 'easy') [code, result] = await easyApply(page);
    else [code, result] = await externalApply(context, page, apply);
  }
  return [code, result];
}
