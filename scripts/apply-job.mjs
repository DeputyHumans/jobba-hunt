      if (!(await typeText(box, EMAIL, { delay: jitter(cfg.pacing.type_delay_ms) })) && (await box.inputValue().catch(() => '')) !== EMAIL) return stop(5, { outcome: 'manual', detail: 'the iCIMS email box did not take the address; nothing was sent' });
