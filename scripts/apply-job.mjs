#!/usr/bin/env node
// Apply runner: submits ONE application the user approved, through LinkedIn Easy Apply, Dice Easy
// Apply (channel dice-easy) or a company-site form: Greenhouse, Lever, Ashby, Workday, appcast,
// Paycor, Paylocity, Workable, Rippling, Walmart, iCIMS, or a per-host `site:<host>` form. It never
// guesses an answer, never follows a company, never solves a CAPTCHA, and never submits twice.
// Workday and iCIMS portals can need a candidate account: one is created only when
// config/apply.json accounts.create is true and the vault (config/vault.json) is unlocked, with the
// password generated by the vault and stored before the sign-up form is sent; otherwise the portal
// goes to the user. Walmart's careers site signs in with a code mailed to the application email (no
// password). Mailed codes and links are read through the mail adapter (config/mail.json, read verbs
// only); none within code_wait_seconds is a hand-off, never a guess. Phenom apply flows (found on a
// `site:<host>` channel by their page) are one page with a step bar: the CV goes up first and alone,
// page alerts are recorded (they are Phenom's refusals), and native selects are set with no key.
// A company-site role whose last run recorded its application URL starts there, not on LinkedIn.
//
// Gates, in order (each refuses before any browser starts):
//   1. The user's decision: a dry run needs "pursue"; a real submit also needs
//      `record-triage approve` (written right after the user's "Apply" in the session).
//   2. One submit per job, ever, including an unverified one (a retry could duplicate).
//   3. The loop halt (halt_until; Dice jobs: the Dice halt) and the daily caps
//      (linkedin_apply / dice_apply / ats_apply).
//   4. The channel's `verified` flag in config/apply.json, set only by `verify` after the user
//      checked a headed dry run of that channel. Unverified channels allow --dry-run only.
//
// Usage:
//   node scripts/apply-job.mjs --job <id> --dry-run [--headed] [--cv <pdf>] [--cover <txt>] [--cover-pdf <pdf>]
//   node scripts/apply-job.mjs --job <id> [--headed]            # real submit
//   node scripts/apply-job.mjs --job <id> --ats-url <https url> [...]  # start at a known application page, not LinkedIn
//   node scripts/apply-job.mjs learn --label "<question>" --answer "<the user's answer>"
//   node scripts/apply-job.mjs check-answers                    # which answer-bank values are still empty
//   node scripts/apply-job.mjs verify --channel <name> --evidence <run dir of a headed dry run of it>
//
// Every attempt outcome, learn and verify is appended to the action log (data/log/actions.jsonl).
//
// Exit codes: 0 submitted, dry run complete, or a command done; 1 error; 2 refused by a gate;
// 3 profile busy; 4 needs_answers (questions listed; nothing submitted); 5 handed to the user
// (unsupported site, account portal, CAPTCHA, vault locked or off, a mailed code that did not come)
// or a closed posting; 6 submit-unverified (do not retry; the user checks); 7 the platform shows
// the job as already applied.

