  if (!known.includes(name) && !/^site:[a-z0-9.-]+$/.test(name)) stop(`unknown channel "${name}" (known: ${known.join(', ')}, or site:<host>)`);
  const resultFile = join(dir, 'result.json');
  let r = null;
  try { r = existsSync(resultFile) ? readJsonFile(resultFile) : null; } catch { r = null; }
