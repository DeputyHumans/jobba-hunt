async function discardEasyApply(page) {
  const dismiss = page.locator('[role="dialog"] button[aria-label="Dismiss"], [role="dialog"] button[aria-label="Close"]').first();
  if (await dismiss.isVisible().catch(() => false)) await dismiss.click();
  await page.waitForTimeout(1200);
  const discard = page.getByRole('button', { name: /^discard$/i }).first();
  if (await discard.isVisible().catch(() => false)) await discard.click();
}

async function easyApply(page) {
  const channel = 'easy';
  if (!dryRun && !cfg.verified?.easy) return [2, { outcome: 'refused', channel, detail: unverified(channel) }];
  const apps = appsCap('linkedin_apply');
  if (!dryRun && !apps.ok) return [2, { outcome: 'refused', channel, detail: 'linkedin_apply applications_per_day cap reached' }];
  await page.getByRole('button', { name: /easy apply/i }).first().click();
  await page.waitForTimeout(2500);
  // Known pre-form interstitial: "Job search safety reminder" with
  // "Review job post" / "Continue applying". Only this exact button is clicked.
  if (await page.evaluate(passInterstitial)) await page.waitForTimeout(2500);
  const filled = [];
  let resumeVerified = false;
  for (let step = 1; step <= cfg.max_steps; step++) {
    if (!(await page.evaluate(markRoot, 'dialog'))) {
      await screenshot(page, 'no-dialog');
      writeFileSync(join(outDir, 'no-dialog.html'), await page.content());
      return [5, { outcome: 'manual', channel, detail: 'Easy Apply dialog not found' }];
    }
    let snap = await page.evaluate(collectForm);
    writeFileSync(join(outDir, `step${step}-dialog.html`), await page.evaluate(() => document.querySelector('[data-hunt-root]')?.outerHTML || ''));
    const blocker = blockerIn(snap);
    if (blocker) { await screenshot(page, blocker); await discardEasyApply(page); return [5, { outcome: 'manual', channel, detail: blocker }]; }
    const plan = planFill(snap.fields, bank, ctx);
    if (plan.missing.length) { await screenshot(page, `step${step}-needs-answers`); await discardEasyApply(page); return [4, { outcome: 'needs_answers', channel, detail: plan.missing, filled }]; }
    await fill(page, plan.actions);
    filled.push(...summary(plan, snap));
    // Resume: always the CV the user approved, uploaded fresh. LinkedIn preselects an older
    // upload (seen in a live dry run) and its "Upload resume" button has no file input:
    // it opens a native file chooser. After upload, the CV's card must be the checked one
    // (or, with no picker, the CV must be visibly attached). Otherwise stop, send nothing.
    snap = await page.evaluate(collectForm);
    const resumeStep = /\bresume\b/i.test(snap.text);
    let uploaded = plan.actions.some((a) => a.action === 'file');
    const uploadBtn = button(snap, /^upload resume$/i);
    const reusable = resumeChoice(snap.fields, basename(cv)).status !== 'missing' && state.cv_uploads[basename(cv)]?.sha === cvSha;
    if (resumeStep && !uploaded && uploadBtn && !reusable) {
      const [chooser] = await Promise.all([page.waitForEvent('filechooser', { timeout: 10000 }), rootBtn(page, uploadBtn).click()]);
      await chooser.setFiles(cv);
      uploaded = true;
      state.cv_uploads[basename(cv)] = { sha: cvSha, at: new Date().toISOString() };
      await page.waitForTimeout(4000);
      await page.evaluate(markRoot, 'dialog');
      snap = await page.evaluate(collectForm);
    } else if (uploaded) {
      await page.waitForTimeout(3000);
      snap = await page.evaluate(collectForm);
    }
    let rc = resumeChoice(snap.fields, basename(cv));
    if (rc.status === 'select') {
      const opt = page.locator(`[data-hunt-key="${rc.key}"][data-hunt-opt="${rc.option.replace(/"/g, '\\"')}"]`);
      const card = opt.locator('xpath=ancestor::*[@role="radio"][1]');
      if (await card.count()) await card.first().click();
      // LinkedIn 2026 resume rows: a div[role=button] card selects the row, beside a hidden radio
      // (the old outer-box click missed a second-row CV twice). resumeChoice
      // below re-reads the picker, so a selection that did not take still stops the run.
      else await selectResumeRow(page, rc.key, rc.option);
      await page.waitForTimeout(1000);
      await page.evaluate(markRoot, 'dialog');
      snap = await page.evaluate(collectForm);
      rc = resumeChoice(snap.fields, basename(cv));
    }
    const cvVisible = snap.text.toLowerCase().includes(basename(cv).toLowerCase().replace(/\.(pdf|docx?)$/, ''));
    // Once the approved CV was confirmed as the selected card on an earlier step, a later
    // step with no picker (a "top choice" page whose hidden text mentions a
    // resume) is not a failure. A step that shows the picker again is always re-checked.
    if (rc.status === 'missing' || rc.status === 'select' || ((uploaded || resumeStep) && rc.status === 'none' && !cvVisible && !resumeVerified)) {
      await screenshot(page, `step${step}-resume-not-selected`);
      await discardEasyApply(page);
      return [5, { outcome: 'manual', channel, detail: `the approved CV (${basename(cv)}) is not the selected resume; nothing sent`, filled }];
    }
    if (rc.status === 'ok') { resumeVerified = true; filled.push({ label: 'Resume selected', value: rc.option, source: 'cv', action: 'radio' }); }
    // Follow guard, independent of the plan: a ticked Follow box gets one untick attempt,
    // then stops the run. Never submit while it is ticked.
    let follow = followBoxesChecked(snap.fields);
    if (follow.length) {
      await fill(page, follow.map((f) => ({ key: f.key, action: 'uncheck', value: null })));
      await page.evaluate(markRoot, 'dialog');
      snap = await page.evaluate(collectForm);
      follow = followBoxesChecked(snap.fields);
    }
    if (follow.length) {
      await screenshot(page, `step${step}-follow-still-ticked`);
      await discardEasyApply(page);
      return [5, { outcome: 'manual', channel, detail: `"${follow[0].label}" is still ticked; nothing sent`, filled }];
    }
    if (snap.fields.some((f) => f.kind === 'checkbox' && /\bfollow\b/i.test(f.label))) filled.push({ label: 'Follow company', value: 'unticked', source: 'never-follow', action: 'uncheck' });
    await screenshot(page, `step${step}`);
    const submit = button(snap, /^submit application$/i);
    if (submit) {
      // Evidence for the user: the selected resume card, then the bottom of the form.
      const picked = page.locator('[data-hunt-root] [role="radio"][aria-checked="true"]').first();
      if (await picked.count()) { await picked.scrollIntoViewIfNeeded().catch(() => {}); await screenshot(page, 'final-resume'); }
      await rootBtn(page, submit).scrollIntoViewIfNeeded().catch(() => {});
      await screenshot(page, 'final-submit');
      if (dryRun) { await discardEasyApply(page); return [0, { outcome: 'dry-run-complete', channel, detail: `stopped before "${submit}"`, filled }]; }
      submitClicked = true;
      await rootBtn(page, submit).click();
      await page.waitForTimeout(jitter([4000, 6000]));
      const text = await page.evaluate(() => document.body.innerText.slice(0, 8000));
      await screenshot(page, 'after-submit');
      if (confirmationIn(text)) {
        // No clicks after a confirmed submit: the confirmation dialog upsells #OpenToWork
        // ("Get started" edits the profile, which is forbidden). Closing the browser is enough.
        recordPost('linkedin_apply', 'applications_per_day', { jobId: id, ...apps.meta });
        return [0, { outcome: 'submitted', channel, filled }];
      }
      return [6, { outcome: 'submit-unverified', channel, detail: 'no confirmation text after Submit; check LinkedIn > My jobs > Applied by hand', filled }];
    }
    const next = button(snap, /^review/i) || button(snap, /^(continue to next step|next|continue)$/i);
    if (!next) { await screenshot(page, 'no-next'); await discardEasyApply(page); return [5, { outcome: 'manual', channel, detail: `no Next/Review/Submit button; buttons: ${snap.buttons.join(' | ')}` }]; }
    const beforeText = snap.text;
    await rootBtn(page, next).click();
    await sleep(jitter(cfg.pacing.step_gap_ms));
    await page.evaluate(markRoot, 'dialog');
    const after = await page.evaluate(collectForm);
    // Stuck guard: the page did not advance. Report the validation messages as questions
    // for the user and stop; never click Next again on the same page (a second click looped).
    if (after.text === beforeText || after.fields.some((f) => f.error)) {
      const errs = after.fields.filter((f) => f.error).map((f) => ({ key: f.key, label: f.label, kind: f.kind, options: f.options, reason: `validation: ${f.error}` }));
      const loose = errs.length ? [] : (await page.evaluate(stuckReport)).map((e) => ({ key: null, label: e.label, kind: 'unknown', options: [], reason: `validation: ${e.error}` }));
      await screenshot(page, `step${step}-stuck`);
      await discardEasyApply(page);
      return [4, { outcome: 'needs_answers', channel, detail: errs.length ? errs : loose.length ? loose : [{ key: null, label: '(page did not advance)', kind: 'unknown', options: [], reason: stuckReason() }], filled }];
    }
  }
  await discardEasyApply(page);
  return [5, { outcome: 'manual', channel, detail: `more than ${cfg.max_steps} steps` }];
}

